function t(key, vars) {
  let s = STR[LANG][key];
  if (s === undefined) s = STR.en[key];
  if (s === undefined) return key;
  if (typeof s === 'function') return s(vars);
  if (vars && typeof s === 'string') s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
  return s;
}

/* Speed in the unit the learner picked (words or characters per minute). */
function fmtSpeed(wpm, withUnit = true) {
  const unit = Settings.get('unit') === 'auto' ? (LANG === 'de' ? 'cpm' : 'wpm') : Settings.get('unit');
  const v = Math.round(unit === 'cpm' ? wpm * 5 : wpm);
  return withUnit ? `${v} ${t(unit)}` : String(v);
}
function speedUnit() {
  const unit = Settings.get('unit') === 'auto' ? (LANG === 'de' ? 'cpm' : 'wpm') : Settings.get('unit');
  return t(unit);
}
