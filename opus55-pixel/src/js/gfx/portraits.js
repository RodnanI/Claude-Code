const Portraits = {
  cache: {},
  get(id) {
    let c = this.cache[id];
    if (c) return c;
    const P = PORTRAITS[id];
    const pt = new Paint(32, 32);
    // warm backdrop wash inside the frame
    for (let y = 0; y < 32; y++) for (let x = 0; x < 32; x++) pt.px(x, y, bayer(x, y) < y / 40 ? '#2a1c16' : '#3a2820');
    if (P) P.rows.forEach((row, y) => { for (let x = 0; x < row.length; x++) { const ch = row[x]; if (ch !== '.' && P.pal[ch]) pt.px(x, y, P.pal[ch]); } });
    c = this.cache[id] = pt.done();
    return c;
  },
};
