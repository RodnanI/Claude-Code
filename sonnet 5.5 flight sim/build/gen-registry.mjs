// Discovers content modules by file suffix and writes src/generated/registry.js.
// Adding a plane, region, kit, scenery type or vehicle means adding one file; nothing else is edited.
import { readdirSync, statSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, relative, dirname, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'src');

const GROUPS = [
  { name: 'AIRCRAFT', dir: 'aircraft/planes', suffix: '.plane.js' },
  { name: 'REGIONS', dir: 'world/regions', suffix: '.region.js' },
  { name: 'KITS', dir: 'world/kits', suffix: '.kit.js' },
  { name: 'SCENERY', dir: 'world/scenery', suffix: '.scenery.js' },
  { name: 'VEHICLES', dir: 'traffic/vehicles', suffix: '.vehicle.js' },
  { name: 'AMBIENT', dir: 'traffic/ambient', suffix: '.ambient.js' },
];

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

export function generate() {
  const lines = ['// AUTO-GENERATED by build/gen-registry.mjs. Do not edit.'];
  const arrays = [];
  let n = 0;
  for (const g of GROUPS) {
    const files = walk(join(src, g.dir)).filter((f) => f.endsWith(g.suffix));
    const ids = [];
    for (const f of files) {
      const id = `m${n++}`;
      const rel = relative(join(src, 'generated'), f).split(sep).join('/');
      lines.push(`import ${id} from '${rel.startsWith('.') ? rel : './' + rel}';`);
      ids.push(id);
    }
    arrays.push(`export const ${g.name} = [${ids.join(', ')}].flat();`);
  }
  lines.push('', ...arrays, '');
  const text = lines.join('\n');
  mkdirSync(join(src, 'generated'), { recursive: true });
  writeFileSync(join(src, 'generated', 'registry.js'), text);
  return text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  generate();
  console.log('registry written');
}
