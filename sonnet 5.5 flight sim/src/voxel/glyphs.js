/** Width of a line of text in glyph pixels, with a gap of `gap` pixels between letters. */
export const textPixels = (text, gap = 1) => Math.max(0, text.length * 5 + (text.length - 1) * gap);

/** Every lit pixel of a line of text as [column, row] with row 0 at the top. */
export function textDots(text, gap = 1) {
  const dots = [];
  for (let k = 0; k < text.length; k++) {
    const g = GLYPHS[text[k].toUpperCase()] || GLYPHS[' '];
    for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) if (g[r][c] === '1') dots.push([k * (5 + gap) + c, r]);
  }
  return dots;
}

/**
 * Text as voxel boxes in a Recipe, standing upright in the x-y plane and readable from +z (or from -z with flip), centered on
 * x = cx with its baseline at y = y0. Horizontal runs of lit pixels are merged into single boxes. px is the pixel size in meters.
 */
export function textBoxes(b, text, cx, y0, z, px, mat, depth = 0.4, o, gap = 1, flip = false) {
  const cols = textPixels(text, gap), w = cols * px;
  for (let r = 0; r < 7; r++) {
    let run = -1;
    const flush = (end) => {
      if (run < 0) return;
      const xa = flip ? cx + w / 2 - end * px : cx - w / 2 + run * px, xb = flip ? cx + w / 2 - run * px : cx - w / 2 + end * px;
      b.box(xa, y0 + (6 - r) * px, z, xb, y0 + (7 - r) * px, z + depth, mat, o);
      run = -1;
    };
    for (let c = 0; c < cols; c++) {
      const k = Math.floor(c / (5 + gap)), lc = c - k * (5 + gap);
      const g = GLYPHS[text[k].toUpperCase()] || GLYPHS[' '];
      const on = lc < 5 && g[r][lc] === '1';
      if (on && run < 0) run = c;
      else if (!on) flush(c);
    }
    flush(cols);
  }
}
