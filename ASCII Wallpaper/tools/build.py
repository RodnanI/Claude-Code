#!/usr/bin/env python3
"""Build steps for the ASCII wallpaper.

  python3 tools/build.py fonts   -> regenerate src/fonts.js from src/fonts/*.woff2
  python3 tools/build.py         -> fonts + inline everything into index.html

index.html is fully self-contained (fonts, engine, scenes, UI) and works
offline from file://.
"""
import base64
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src')

# label, file, css family, weight, advance multiplier
FONTS = [
    ('JetBrains Mono', 'jetbrains-mono-500.woff2', 'AWJetBrains', 500),
    ('DejaVu Sans Mono', 'dejavu-400.woff2', 'AWDejaVu', 400),
    ('IBM Plex Mono', 'ibm-plex-mono-500.woff2', 'AWPlex', 500),
    ('Iosevka (narrow)', 'iosevka-500.woff2', 'AWIosevka', 500),
]


def build_fonts():
    out = ['/* generated by tools/build.py - embedded ASCII subsets of OFL / Bitstream-licensed fonts */',
           'window.ASCII = window.ASCII || {};',
           'ASCII.fonts = [']
    for label, fn, fam, w in FONTS:
        b64 = base64.b64encode(open(os.path.join(SRC, 'fonts', fn), 'rb').read()).decode()
        out.append(f"  {{ label: '{label}', family: '{fam}', weight: {w}, b64: '{b64}' }},")
    out.append('];')
    open(os.path.join(SRC, 'fonts.js'), 'w').write('\n'.join(out) + '\n')


def inline_html():
    shell = open(os.path.join(SRC, 'shell.html')).read()

    def repl(m):
        path = os.path.join(SRC, m.group(1))
        code = open(path).read()
        return '<script>\n' + code.replace('</script', '<\\/script') + '\n</script>'

    html = re.sub(r'<script src="([^"]+)"></script>', repl, shell)
    open(os.path.join(ROOT, 'index.html'), 'w').write(html)
    print('index.html', len(html) // 1024, 'KB')


if __name__ == '__main__':
    build_fonts()
    if len(sys.argv) < 2 or sys.argv[1] != 'fonts':
        inline_html()
